// Builds `dist/svg/pix-sprite.svg` and `dist/icons.js` from the icons of `./icons`.
//
// Each icon has its own folder, named after the icon (the `@name` of PixIcon):
// `icons/<name>/default.svg` (outlined) and, optionally, `icons/<name>/plain.svg`
// (filled). They become the sprite symbols `<name>` and `<name>_plain`, which
// `dist/icons.js` maps every icon name to.
import { mkdir, readdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import SVGSpriter from 'svg-sprite';
import { optimize } from 'svgo';

import svgoConfig from './svgo.config.js';

const toolingDir = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(toolingDir, 'icons');
const distDir = join(toolingDir, '../../dist');
const spriteOutput = join(distDir, 'svg/pix-sprite.svg');
const iconsOutput = join(distDir, 'icons.js');

const VARIANTS = { 'default.svg': '', 'plain.svg': '_plain' };

const spriter = new SVGSpriter({
  log: false,
  // Files are added with `<name>/<variant>.svg` as their name: see below.
  shape: {
    id: {
      generator: (file) => {
        const [name, variant] = file.split(/[\\/]/);
        return `${name}${VARIANTS[variant]}`;
      },
    },
  },
  mode: { defs: { inline: true, bust: false } },
});

const icons = {};
const names = (await readdir(iconsDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

for (const name of names) {
  const files = await readdir(join(iconsDir, name));
  const unexpected = files.filter((file) => !(file in VARIANTS));
  if (unexpected.length > 0) {
    throw new Error(
      `icons/${name}: unexpected ${unexpected.join(', ')} (only ${Object.keys(VARIANTS).join(' and ')})`,
    );
  }
  if (!files.includes('default.svg')) {
    throw new Error(`icons/${name}: missing default.svg`);
  }

  for (const file of files) {
    const path = join(iconsDir, name, file);
    spriter.add(path, `${name}/${file}`, await readFile(path, 'utf8'));
  }

  icons[name] = files.includes('plain.svg')
    ? { default: name, plainIcon: `${name}_plain` }
    : { default: name };
}

const { result } = await spriter.compileAsync();
const { data: sprite } = optimize(result.defs.sprite.contents.toString(), svgoConfig);

const iconsModule = [
  '// Generated by tooling/generate-svg-sprite/build-sprite.mjs from tooling/generate-svg-sprite/icons: do not edit.',
  'export const ICONS = {',
  ...Object.entries(icons).map(([name, def]) => `  ${name}: ${JSON.stringify(def)},`),
  '};',
  '',
].join('\n');

// Every framework package runs this build (on `prepare` too), possibly in
// parallel: write then rename, so no build ever reads a half-written file.
async function writeAtomically(output, content) {
  const tmpOutput = `${output}.${process.pid}.tmp`;
  await mkdir(dirname(output), { recursive: true });
  await writeFile(tmpOutput, content);
  await rename(tmpOutput, output);
}

await writeAtomically(spriteOutput, sprite);
await writeAtomically(iconsOutput, iconsModule);
console.log(`${names.length} icons → ${spriteOutput}, ${iconsOutput}`);
